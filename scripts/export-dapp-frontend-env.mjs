function kv(key, value) {
  return `${key}=${value ?? ''}`;
}

function normalizeUrl(value) {
  const raw = String(value || '').trim();
  if (!raw || raw.startsWith('<')) return raw || '<https_domain>';
  try {
    return new URL(raw).toString().replace(/\/$/, '');
  } catch {
    return '<https_domain>';
  }
}

function absoluteUrl(base, pathname) {
  if (!base || base.startsWith('<')) return '<https_api_domain>';
  try {
    return new URL(pathname, `${String(base).replace(/\/+$/, '')}/`).toString();
  } catch {
    return '<https_api_domain>';
  }
}
